/**
 * Recurring / Subscription occurrences as automatic billing uses them: the
 * amount of each occurrence is its period's share of the recurring contract
 * value (generated by the existing schedule generation, never the whole
 * contract), and {@link BillingOccurrenceServiceImpl#requireRecurringOccurrenceBillable(UUID)}
 * confirms an occurrence can still be billed as generated.
 */
@ExtendWith(MockitoExtension.class)
@MockitoSettings(strictness = Strictness.LENIENT)
class RecurringOccurrenceBillabilityTest {

    @Mock private BillingScheduleRepository scheduleRepository;
    @Mock private BillingRecurringConfigurationRepository recurringRepository;
    @Mock private BillingConfigurationRepository configurationRepository;
    @InjectMocks private BillingOccurrenceServiceImpl service;

    private BillingConfiguration configuration;

    @BeforeEach
    void setUp() {
        configuration = BillingConfiguration.builder()
                .billingConfigurationId(UUID.randomUUID())
                .approvalStatus(ApprovalStatus.APPROVED)
                .currency(CurrencyMaster.builder().currencyId(UUID.randomUUID()).currencyCode("INR").build())
                .build();
    }

    private static BillingFrequencyMaster frequency(String name, int months) {
        return BillingFrequencyMaster.builder()
                .billingFrequencyId(UUID.randomUUID())
                .billingFrequencyName(name)
                .durationUnit(RenewalDurationUnit.MONTHS)
                .durationValue(months)
                .build();
    }

    private BillingRecurringConfiguration recurring(String contractValue, LocalDate start, LocalDate end,
            BillingFrequencyMaster frequency) {
        return BillingRecurringConfiguration.builder()
                .recurringConfigurationId(UUID.randomUUID())
                .billingConfiguration(configuration)
                .recurringName("Managed Support Retainer")
                .contractValue(contractValue != null ? new BigDecimal(contractValue) : null)
                .billingFrequency(frequency)
                .recurringStartDate(start)
                .recurringEndDate(end)
                .isActive(true)
                .build();
    }

    // ================================================================ amounts from the existing generation

    @Nested
    class GeneratedAmounts {

        @SuppressWarnings("unchecked")
        private List<BillingSchedule> generate(BillingRecurringConfiguration recurring) {
            when(configurationRepository.findById(configuration.getBillingConfigurationId()))
                    .thenReturn(Optional.of(configuration));
            when(recurringRepository.findByBillingConfigurationAndIsActiveTrue(configuration))
                    .thenReturn(Optional.of(recurring));
            when(scheduleRepository.findByRecurringConfigurationAndIsActiveTrueOrderByPeriodNumberAsc(recurring))
                    .thenReturn(List.of());

            service.generateOccurrencesForRecurring(configuration.getBillingConfigurationId());

            ArgumentCaptor<Collection<BillingSchedule>> saved = ArgumentCaptor.forClass(Collection.class);
            verify(scheduleRepository, atLeastOnce()).saveAll(saved.capture());
            return saved.getAllValues().stream().flatMap(Collection::stream).toList();
        }

        @Test
        void monthlyRetainer_eachOccurrenceIsItsMonthsShare_neverTheWholeContract() {
            List<BillingSchedule> months = generate(recurring("1200000.00",
                    LocalDate.of(2026, 1, 1), LocalDate.of(2026, 12, 31), frequency("Monthly", 1)));

            assertThat(months).hasSize(12);
            assertThat(months).allSatisfy(month -> {
                assertThat(month.getBillingAmount()).isLessThan(new BigDecimal("1200000.00"));
                assertThat(month.getPeriodEndDate()).isEqualTo(
                        month.getPeriodStartDate().plusMonths(1).minusDays(1));
                assertThat(month.getRecurringConfiguration()).isNotNull();
            });
            // January: 31 of 365 days.
            assertThat(months.get(0).getBillingAmount()).isEqualByComparingTo("101917.81");
            assertThat(months.stream().map(BillingSchedule::getBillingAmount).reduce(BigDecimal.ZERO, BigDecimal::add))
                    .isEqualByComparingTo("1200000.00");
        }

        @Test
        void quarterlyRetainer_usesItsOwnStoredQuarterPeriods() {
            List<BillingSchedule> quarters = generate(recurring("400000.00",
                    LocalDate.of(2026, 4, 1), LocalDate.of(2027, 3, 31), frequency("Quarterly", 3)));

            assertThat(quarters).extracting(BillingSchedule::getPeriodStartDate).containsExactly(
                    LocalDate.of(2026, 4, 1), LocalDate.of(2026, 7, 1), LocalDate.of(2026, 10, 1),
                    LocalDate.of(2027, 1, 1));
            assertThat(quarters).extracting(BillingSchedule::getBillingDate).containsExactly(
                    LocalDate.of(2026, 6, 30), LocalDate.of(2026, 9, 30), LocalDate.of(2026, 12, 31),
                    LocalDate.of(2027, 3, 31));
            assertThat(quarters.stream().map(BillingSchedule::getBillingAmount).reduce(BigDecimal.ZERO, BigDecimal::add))
                    .isEqualByComparingTo("400000.00");
        }
    }

    // ================================================================ billability

    @Nested
    class Billability {

        private final List<BillingSchedule> activeOfConfiguration = new ArrayList<>();
        private BillingRecurringConfiguration recurring;

        @BeforeEach
        void setUp() {
            recurring = recurring("1200000.00", LocalDate.of(2026, 1, 1), LocalDate.of(2026, 12, 31),
                    frequency("Monthly", 1));
            when(scheduleRepository.findByBillingConfigurationAndIsActiveTrueOrderByPeriodNumberAsc(configuration))
                    .thenReturn(activeOfConfiguration);
            when(scheduleRepository.findByRecurringConfigurationAndIsActiveTrueOrderByPeriodNumberAsc(any()))
                    .thenAnswer(invocation -> activeOfConfiguration.stream()
                            .filter(s -> s.getRecurringConfiguration() == invocation.getArgument(0))
                            .toList());
        }

        private BillingSchedule occurrence(BillingRecurringConfiguration of, LocalDate start, LocalDate end,
                String amount, BillingPeriodStatus status) {
            BillingSchedule occurrence = BillingSchedule.builder()
                    .billingScheduleId(UUID.randomUUID())
                    .billingConfiguration(configuration)
                    .recurringConfiguration(of)
                    .periodNumber(activeOfConfiguration.size() + 1)
                    .periodStartDate(start)
                    .periodEndDate(end)
                    .billingDate(end)
                    .billingAmount(amount != null ? new BigDecimal(amount) : null)
                    .periodStatus(status)
                    .isActive(true)
                    .build();
            activeOfConfiguration.add(occurrence);
            when(scheduleRepository.findById(occurrence.getBillingScheduleId())).thenReturn(Optional.of(occurrence));
            return occurrence;
        }

        private BillingSchedule month(int month, String amount, BillingPeriodStatus status) {
            LocalDate start = LocalDate.of(2026, month, 1);
            return occurrence(recurring, start, start.withDayOfMonth(start.lengthOfMonth()), amount, status);
        }

        private void check(BillingSchedule occurrence) {
            service.requireRecurringOccurrenceBillable(occurrence.getBillingScheduleId());
        }

        @Test
        void dueMonth_ofAnActiveRetainer_isBillable() {
            month(9, "98630.14", BillingPeriodStatus.INVOICED);
            BillingSchedule october = month(10, "101917.81", BillingPeriodStatus.SCHEDULED);

            assertThatCode(() -> check(october)).doesNotThrowAnyException();
        }

        @Test
        void renewal_isCheckedAgainstItsOwnContractValue() {
            month(12, "101917.81", BillingPeriodStatus.INVOICED);
            BillingRecurringConfiguration renewal = recurring("150000.00", LocalDate.of(2027, 1, 1),
                    LocalDate.of(2027, 1, 31), frequency("Monthly", 1));
            BillingSchedule january = occurrence(renewal, LocalDate.of(2027, 1, 1), LocalDate.of(2027, 1, 31),
                    "150000.00", BillingPeriodStatus.SCHEDULED);

            assertThatCode(() -> check(january)).doesNotThrowAnyException();
        }

        @Test
        void renewalOverlappingAnAlreadyBilledPeriod_isNotBilledTwice() {
            month(12, "101917.81", BillingPeriodStatus.INVOICED);
            BillingRecurringConfiguration renewal = recurring("150000.00", LocalDate.of(2026, 12, 15),
                    LocalDate.of(2027, 1, 14), frequency("Monthly", 1));
            BillingSchedule overlapping = occurrence(renewal, LocalDate.of(2026, 12, 15), LocalDate.of(2027, 1, 14),
                    "150000.00", BillingPeriodStatus.SCHEDULED);

            assertThatThrownBy(() -> check(overlapping))
                    .isInstanceOf(GlobalExceptionHandler.ValidationException.class)
                    .hasMessageContaining("overlaps billing period 2026-12-01 to 2026-12-31 (INVOICED)");
        }

        @Test
        void scheduleRegeneratedFromTheFullContractValue_isNotBilled() {
            // Jan-Jun invoiced (600000); an update regenerated Jul-Dec from the full 1200000.
            for (int m = 1; m <= 6; m++) {
                month(m, "100000.00", BillingPeriodStatus.INVOICED);
            }
            BillingSchedule july = month(7, "200000.00", BillingPeriodStatus.SCHEDULED);
            for (int m = 8; m <= 12; m++) {
                month(m, "200000.00", BillingPeriodStatus.SCHEDULED);
            }

            assertThatThrownBy(() -> check(july))
                    .hasMessageContaining("total 1800000.00")
                    .hasMessageContaining("more than the Recurring contract value 1200000.00");
        }

        @Test
        void periodOutsideTheRecurringTerm_isNotBilled() {
            BillingSchedule beyond = occurrence(recurring, LocalDate.of(2027, 1, 1), LocalDate.of(2027, 1, 31),
                    "100000.00", BillingPeriodStatus.SCHEDULED);

            assertThatThrownBy(() -> check(beyond))
                    .hasMessageContaining("lies outside the recurring term 2026-01-01 to 2026-12-31");
        }

        @Test
        void inactiveRecurringConfiguration_isNotBilled() {
            BillingSchedule october = month(10, "101917.81", BillingPeriodStatus.SCHEDULED);
            recurring.setIsActive(false);

            assertThatThrownBy(() -> check(october)).hasMessageContaining("is no longer active");
        }

        @Test
        void recurringConfigurationOfAnotherBillingConfiguration_isNotBilled() {
            BillingSchedule october = month(10, "101917.81", BillingPeriodStatus.SCHEDULED);
            recurring.setBillingConfiguration(BillingConfiguration.builder()
                    .billingConfigurationId(UUID.randomUUID()).build());

            assertThatThrownBy(() -> check(october))
                    .hasMessageContaining("belongs to a Recurring configuration of another Billing Configuration");
        }

        @Test
        void occurrenceWithoutRecurringConfiguration_isNotBilled() {
            BillingSchedule orphan = occurrence(null, LocalDate.of(2026, 10, 1), LocalDate.of(2026, 10, 31),
                    "100000.00", BillingPeriodStatus.SCHEDULED);

            assertThatThrownBy(() -> check(orphan)).hasMessageContaining("has no Recurring configuration");
        }

        @Test
        void zeroAmountOrMissingCurrency_isNotBilled() {
            BillingSchedule zero = month(10, "0.00", BillingPeriodStatus.SCHEDULED);
            assertThatThrownBy(() -> check(zero)).hasMessageContaining("has no positive billing amount");

            BillingSchedule november = month(11, "98630.14", BillingPeriodStatus.SCHEDULED);
            configuration.setCurrency(null);
            assertThatThrownBy(() -> check(november)).hasMessageContaining("No currency is configured");
        }
    }
}
